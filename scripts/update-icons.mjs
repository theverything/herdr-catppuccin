#!/usr/bin/env node
// Rebuilds mods/catppuccin-files/icons and both mods' icon-map.js from a checkout of
// https://github.com/catppuccin/vscode-icons:
//
//   node scripts/update-icons.mjs path/to/vscode-icons
//
// Herdr doesn't let a mod import from another mod's folder, so catppuccin-changes
// gets copies of icon-map.js and icons.js. The SVGs stay in catppuccin-files.
//
// The association tables are TypeScript object literals. They are read as data
// (tokenized and parsed as JSON), so nothing from the checkout is executed.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FLAVORS = ["latte", "frappe", "macchiato", "mocha"];

// VS Code resolves languageIds through the extensions its languages claim. Herdr
// has no languages, so the ids whose icon doesn't already list these need them.
const LANGUAGE_EXTENSIONS = {
  diff: ["diff"],
  hxml: ["hxml"],
  hlsl: ["hlsl", "hlsli"],
  wgsl: ["wgsl"],
  vb: ["vb"],
};

const source = process.argv[2];
if (!source || !existsSync(join(source, "icons", "mocha"))) {
  console.error("usage: node scripts/update-icons.mjs path/to/vscode-icons");
  process.exit(1);
}
const mods = join(dirname(fileURLToPath(import.meta.url)), "..", "mods");
const mod = join(mods, "catppuccin-files"), changes = join(mods, "catppuccin-changes");

// The object literal assigned to `name` in a TypeScript file, as a plain object.
function readTable(file, name) {
  const text = readFileSync(join(source, "src", "defaults", file), "utf8");
  const marker = new RegExp(`const ${name}: \\w+ = \\{`).exec(text);
  if (!marker) throw new Error(`${name} not found in ${file}`);
  const start = marker.index + marker[0].length - 1;
  const end = text.indexOf("\n}\n", start);
  if (end < 0) throw new Error(`end of ${name} not found in ${file}`);
  const json = text.slice(start, end + 2)
    .replace(/\/\/[^\n]*|\/\*[\s\S]*?\*\/|'(?:[^'\\]|\\.)*'|[A-Za-z_$][\w$-]*(?=\s*:)/g, token => {
      if (token.startsWith("//") || token.startsWith("/*")) return "";
      return JSON.stringify(token[0] === "'" ? token.slice(1, -1).replace(/\\'/g, "'") : token);
    })
    .replace(/,(\s*[}\]])/g, "$1");
  return JSON.parse(json);
}

const names = {}, extensions = {}, folders = {};
const fileIcons = readTable("fileIcons.ts", "fileIcons");
const folderIcons = readTable("folderIcons.ts", "folderIcons");
for (const [icon, entry] of Object.entries(fileIcons)) {
  for (const name of entry.fileNames ?? []) names[name.toLowerCase()] = icon;
  for (const ext of entry.fileExtensions ?? []) extensions[ext.toLowerCase()] = icon;
}
for (const [icon, entry] of Object.entries(fileIcons))
  for (const id of entry.languageIds ?? [])
    for (const ext of LANGUAGE_EXTENSIONS[id] ?? []) extensions[ext] ??= icon;
for (const [icon, entry] of Object.entries(folderIcons))
  for (const name of entry.folderNames ?? []) folders[name.toLowerCase()] = `folder_${icon}`;

// Every association must point at a real icon, in both its closed and open form.
const has = icon => existsSync(join(source, "icons", "mocha", `${icon}.svg`));
const missing = [
  ...Object.values(names).concat(Object.values(extensions)).filter(icon => !has(icon)),
  ...Object.values(folders).flatMap(icon => [icon, `${icon}_open`]).filter(icon => !has(icon)),
  ...["_file", "_folder", "_folder_open"].filter(icon => !has(icon)),
];
if (missing.length) throw new Error(`missing icons: ${[...new Set(missing)].join(", ")}`);

rmSync(join(mod, "icons"), { recursive: true, force: true });
mkdirSync(join(mod, "icons"), { recursive: true });
for (const flavor of FLAVORS) cpSync(join(source, "icons", flavor), join(mod, "icons", flavor), { recursive: true });
cpSync(join(source, "LICENSE"), join(mod, "icons", "LICENSE"));

const { version } = JSON.parse(readFileSync(join(source, "package.json"), "utf8"));
const table = (name, map) => `export const ${name} = new Map(${JSON.stringify(Object.entries(map).sort(([a], [b]) => (a < b ? -1 : 1)))});\n`;
writeFileSync(join(mod, "icon-map.js"),
  `// Generated by scripts/update-icons.mjs from catppuccin/vscode-icons ${version} (MIT). Don't edit.\n`
  + table("fileNames", names) + table("fileExtensions", extensions) + table("folderNames", folders));

cpSync(join(mod, "icon-map.js"), join(changes, "icon-map.js"));
cpSync(join(mod, "icons.js"), join(changes, "icons.js"));

console.log(`vscode-icons ${version}: ${Object.keys(names).length} file names, ${Object.keys(extensions).length} extensions, ${Object.keys(folders).length} folder names`);
